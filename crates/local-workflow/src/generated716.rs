//! Private generated previews from trusted in-process producers only.
//! Deliberately distinct from candidate.hwpx consumed by publish/diff.
use super::*;
use std::io::{Seek as _,SeekFrom};
const PREVIEW:&str="generated-preview.hwpx";
const PROFILE:&str="hwpx-agent.local-generated-preview/unqualified-v1";
#[derive(Clone,Debug,Eq,PartialEq)]
pub struct GeneratedPreviewReceipt{
    pub profile:&'static str,pub operation_id:String,pub workspace_binding_sha256:String,
    pub source:FileIdentity,pub preview:FileIdentity,pub publication_or_revision_authority:bool,
}
fn read_identity(file:&mut File,max:u64)->Result<FileIdentity,WorkflowError>{
    let meta=file.metadata().map_err(|_|WorkflowError::Io)?;
    if !meta.is_file()||meta.len()==0||meta.len()>max{return Err(WorkflowError::File);}
    file.seek(SeekFrom::Start(0)).map_err(|_|WorkflowError::Io)?;
    let mut hash=Sha256::new();let mut size=0u64;let mut bytes=[0u8;COPY_BUFFER_BYTES];
    loop{let n=file.read(&mut bytes).map_err(|_|WorkflowError::Io)?;if n==0{break;}
        size=size.checked_add(n as u64).filter(|v|*v<=max).ok_or(WorkflowError::File)?;hash.update(&bytes[..n]);}
    Ok(FileIdentity{sha256:hex::encode(hash.finalize()),size_bytes:size})
}
fn open_read(root:&Path,path:&Path)->Result<File,WorkflowError>{
    reject_links_between(root,path)?;
    let resolved=path.canonicalize().map_err(|_|WorkflowError::File)?;
    if !resolved.starts_with(root){return Err(WorkflowError::Path);}
    let mut options=OpenOptions::new();options.read(true);
    #[cfg(windows)]{use std::os::windows::fs::OpenOptionsExt as _;options.share_mode(1);}
    options.open(resolved).map_err(|_|WorkflowError::Io)
}
impl LocalWorkflow{
    fn generated_receipt(&self,operation_id:&str,source:FileIdentity,preview:FileIdentity)->Result<GeneratedPreviewReceipt,WorkflowError>{
        let root=self.root.to_str().ok_or(WorkflowError::Path)?;
        #[cfg(windows)]let root=root.replace('/',"\\").to_lowercase();
        #[cfg(not(windows))]let root=root.to_owned();
        Ok(GeneratedPreviewReceipt{profile:PROFILE,operation_id:operation_id.to_owned(),
            workspace_binding_sha256:bound_digest("hwpx-agent.private-generated-workspace/v1",&[&root]),
            source,preview,publication_or_revision_authority:false})
    }
    /// Trusted host data only. The public bridge accepts no generated byte/XML/path input.
    /// An authenticated producer must still check its own ACL/head before and after this I/O.
    /// # Errors
    /// Requires the exact existing managed source, bounded verified output, no legacy
    /// candidate, and create-new preview. Failed partial private files are preserved.
    pub fn stage_generated_preview(&self,operation_id:&str,source_sha:&[u8;32],preview_sha:&[u8;32],bytes:&[u8])
        ->Result<GeneratedPreviewReceipt,WorkflowError>{
        if source_sha==&[0;32]||preview_sha==&[0;32]{return Err(WorkflowError::Digest);}
        if bytes.is_empty()||bytes.len()as u64>self.max_file_bytes{return Err(WorkflowError::File);}
        if &<[u8;32]>::from(Sha256::digest(bytes))!=preview_sha{return Err(WorkflowError::Digest);}
        let operation=self.operation_directory(operation_id)?;
        match fs::symlink_metadata(operation.join(MaterializeSlot::Candidate.file_name())){
            Ok(_)=>return Err(WorkflowError::OutputExists),
            Err(e)if e.kind()==std::io::ErrorKind::NotFound=>{},
            Err(_)=>return Err(WorkflowError::Io),
        }
        let source_path=operation.join(MaterializeSlot::Source.file_name());
        // Keep the managed source handle open; Windows denies new writes/deletes.
        let mut source_file=open_read(&self.root,&source_path)?;
        let source=read_identity(&mut source_file,self.max_file_bytes)?;
        if source.sha256!=hex::encode(source_sha){return Err(WorkflowError::Digest);}
        let destination=operation.join(PREVIEW);reject_links_between(&self.root,&destination)?;
        let mut options=OpenOptions::new();options.read(true).write(true).create_new(true);
        #[cfg(windows)]{use std::os::windows::fs::OpenOptionsExt as _;options.share_mode(1);}
        let mut output=options.open(&destination).map_err(|e|if e.kind()==std::io::ErrorKind::AlreadyExists{
            WorkflowError::OutputExists}else{WorkflowError::Io})?;
        for chunk in bytes.chunks(COPY_BUFFER_BYTES){output.write_all(chunk).map_err(|_|WorkflowError::Io)?;}
        output.sync_all().map_err(|_|WorkflowError::Io)?;
        let preview=read_identity(&mut output,self.max_file_bytes)?;
        if preview.sha256!=hex::encode(preview_sha)||preview.size_bytes!=bytes.len()as u64
            ||identify_existing(&self.root,&source_path,self.max_file_bytes)?!=source
            ||identify_existing(&self.root,&destination,self.max_file_bytes)?!=preview{return Err(WorkflowError::PublicationIncomplete);}
        self.generated_receipt(operation_id,source,preview)
    }
    /// Read-only identity check after reopening the workspace. No byte delivery or publication.
    /// # Errors
    /// Refuses missing/changed/linked source or preview, invalid IDs and every configured limit.
    pub fn inspect_generated_preview(&self,operation_id:&str,source_sha:&[u8;32],preview_sha:&[u8;32])
        ->Result<GeneratedPreviewReceipt,WorkflowError>{
        let operation=self.operation_directory(operation_id)?;
        let mut source=open_read(&self.root,&operation.join(MaterializeSlot::Source.file_name()))?;
        let source=read_identity(&mut source,self.max_file_bytes)?;
        let mut preview=open_read(&self.root,&operation.join(PREVIEW))?;
        let preview=read_identity(&mut preview,self.max_file_bytes)?;
        if source_sha==&[0;32]||preview_sha==&[0;32]||source.sha256!=hex::encode(source_sha)
            ||preview.sha256!=hex::encode(preview_sha){return Err(WorkflowError::Digest);}
        self.generated_receipt(operation_id,source,preview)
    }
}
